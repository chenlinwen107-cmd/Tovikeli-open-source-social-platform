package com.contentplatform.backend.adapter

/**
 * Platform-independent, normalized author data as obtained from an external
 * platform by an Adapter.
 *
 * This is a pure fact carrier:
 *  - immutable Kotlin data class, no business methods
 *  - NO PublicId, no Repository/Entity, no Spring/JDBC/PostgreSQL type
 *  - NO policy decisions, NO domain identity generation
 *
 * Field semantics (external vocabulary; mapping to Domain [Author] is the
 * Application Normalizer's responsibility, not implemented here):
 *  - [sourceAuthorId]: external author id -> Author.sourceAuthorId
 *  - [name]: author display/account name
 *  - [username]: external username, preserved verbatim
 *  - [displayName]: optional external display name
 *  - [avatarUrl] / [profileUrl]: external avatar/profile URLs
 *    (Domain uses `avatar` / `url`; the mapping is done later, not here)
 *  - [bio]: optional bio text
 *  - [metadata]: only explicitly selected, platform-specific, serializable
 *    values. MUST NOT hold an entire API response / SDK object / JSON node.
 *
 * Identity is (instance context + [sourceAuthorId]); the final au_ PublicId is
 * generated by the Domain Factory, never here.
 */
data class ExternalAuthorInput(
    val instanceRef: ExternalInstanceRef,
    val sourceAuthorId: String,
    val name: String,
    val username: String,
    val displayName: String? = null,
    val avatarUrl: String? = null,
    val profileUrl: String? = null,
    val bio: String? = null,
    val metadata: Map<String, Any?> = emptyMap()
)
