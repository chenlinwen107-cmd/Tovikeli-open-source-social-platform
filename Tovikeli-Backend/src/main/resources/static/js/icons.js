/** The registered icon names, in registration order. */
export const ICON_NAMES = Object.freeze(Object.keys(ICONS));

/** Builds one SVG child element from an artwork spec. */
function buildNode(spec) {
  const element = document.createElementNS(SVG_NS, spec.tag);
  for (const [name, value] of Object.entries(spec.attrs)) {
    element.setAttribute(name, value);
  }
  return element;
}

/**
 * Creates an inline icon element.
 *
 * @param {string} name one of `ICON_NAMES`
 * @param {{
 *   size?: number|string,
 *   class?: string,
 *   strokeWidth?: number,
 *   title?: string,
 * }} [options]
 *   - `size`: width/height for this icon (number = px). Omit to use the shared
 *     `.icon` CSS size.
 *   - `class`: extra class name(s) appended to the base `icon` class.
 *   - `strokeWidth`: overrides the 1.5 baseline.
 *   - `title`: when set, the icon is exposed as a labelled `img` instead of
 *     being decorative.
 * @returns {SVGSVGElement}
 * @throws {RangeError} when `name` is not registered.
 */
export function icon(name, options = {}) {
  const artwork = ICONS[name];
  if (!artwork) {
    throw new RangeError(`Unknown icon: ${name}`);
  }

  const { size, class: extraClass, strokeWidth = DEFAULT_STROKE_WIDTH, title } = options;

  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', String(strokeWidth));
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', extraClass ? `icon ${extraClass}` : 'icon');

  if (size !== undefined && size !== null) {
    const length = typeof size === 'number' ? `${size}px` : size;
    // Inline style so the per-call size wins over the shared `.icon` rule.
    svg.style.width = length;
    svg.style.height = length;
  }

  if (title) {
    svg.setAttribute('role', 'img');
    const titleEl = document.createElementNS(SVG_NS, 'title');
    titleEl.textContent = title;
    svg.append(titleEl);
  } else {
    svg.setAttribute('aria-hidden', 'true');
  }

  for (const spec of artwork) {
    svg.append(buildNode(spec));
  }

  return svg;
}

export default icon;
